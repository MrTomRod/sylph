#!/usr/bin/env python3
"""Deterministically regenerate the fixtures in this directory.

Python standard library only. All randomness comes from the fixed-seed
xorshift64 below, so the output is byte-for-byte reproducible.

Run from the crate root:

    python3 tests/golden/gen_fixtures.py

The fixtures are small (a few KB each) and are committed together with the
goldens produced from them (`sketches.golden.txt`, generated by the
pre-refactor code, see tests/golden_parity.rs).
"""

import os

HERE = os.path.dirname(os.path.abspath(__file__))
M64 = (1 << 64) - 1


class Rng:
    """xorshift64, fixed seed."""

    def __init__(self, seed):
        self.s = seed & M64 or 1

    def next(self):
        s = self.s
        s ^= (s << 13) & M64
        s ^= s >> 7
        s ^= (s << 17) & M64
        self.s = s
        return s

    def base(self):
        return "ACGT"[self.next() % 4]

    def seq(self, n):
        return "".join(self.base() for _ in range(n))


def noisy(seq):
    """N bases, lower-case bases and an IUPAC code, all mapped by BYTE_TO_SEQ."""
    out = []
    for i, b in enumerate(seq):
        if i % 37 == 0:
            out.append("N")
        elif i % 53 == 0:
            out.append(b.lower())
        elif i % 89 == 0:
            out.append("R")
        else:
            out.append(b)
    return "".join(out)


def write(path, text):
    with open(os.path.join(HERE, path), "w", newline="\n") as f:
        f.write(text)
    print("%-28s %6d bytes" % (path, len(text.encode())))


def fastq(records):
    """records: list of (name, seq) or (name, seq, qual)."""
    out = []
    for rec in records:
        name, seq = rec[0], rec[1]
        qual = rec[2] if len(rec) > 2 else "I" * len(seq)
        out.append("@%s\n%s\n+\n%s\n" % (name, seq, qual))
    return "".join(out)


def fasta(records):
    out = []
    for name, seq in records:
        out.append(">%s\n" % name)
        for i in range(0, len(seq), 70):
            out.append(seq[i : i + 70] + "\n")
    return "".join(out)


def main():
    # ---- single-end reads -------------------------------------------------
    # Covers: shorter than k, exactly k, slightly longer than k (for both
    # k = 21 and k = 31), ambiguous/lower-case bases, reads over 400 bp (which
    # switch off the double-k-mer signature), and a read that is all N.
    rng = Rng(0x5EED_0001)
    specs = [
        ("short20", 20, "plain"),
        ("exactly21", 21, "plain"),
        ("just22", 22, "plain"),
        ("exactly31", 31, "plain"),
        ("just32", 32, "plain"),
        ("just35", 35, "plain"),
        ("noisy100", 100, "noisy"),
        ("mid250", 250, "plain"),
        ("over400", 401, "plain"),
        ("long450", 450, "noisy"),
        ("alln60", 60, "alln"),
        ("lower80", 80, "lower"),
    ]
    recs = []
    for name, n, kind in specs:
        seq = rng.seq(n)
        if kind == "noisy":
            seq = noisy(seq)
        elif kind == "alln":
            seq = "N" * n
        elif kind == "lower":
            seq = seq.lower()
        recs.append((name, seq))
    write("reads_mixed.fq", fastq(recs))

    # ---- duplicate reads --------------------------------------------------
    # 8 identical copies of A, 3 copies of B, 5 reads sharing a common 80 bp
    # core behind prefixes of different lengths (same k-mers, different
    # double-k-mer signatures -> the MAX_DEDUP_COUNT escape is reached), plus
    # one unique read.
    rng = Rng(0x5EED_0002)
    a = rng.seq(120)
    b = rng.seq(150)
    core = rng.seq(80)
    c = rng.seq(120)
    shared = [rng.seq(2 * i) + core for i in range(5)]
    recs = []
    for i in range(8):
        recs.append(("dup_a%d" % i, a))
    for i in range(3):
        recs.append(("dup_b%d" % i, b))
    for i in range(4):
        recs.append(("shared_core%d" % i, shared[i]))
    # Repeat of the signature seen when the count reached MAX_DEDUP_COUNT (4):
    # this exercises the threshold-escape boundary itself, not just the
    # "distinct signature" path above.
    recs.append(("shared_core3_again", shared[3]))
    recs.append(("shared_core4", shared[4]))
    recs.append(("shared_core0_again", shared[0]))
    recs.append(("unique_c", c))
    write("reads_dups.fq", fastq(recs))

    # ---- within-read repeats ---------------------------------------------
    # Tandem unit repeat, an internal duplicated segment, a duplicated 30 bp
    # block and a low-complexity ACGT repeat.
    rng = Rng(0x5EED_0003)
    unit = rng.seq(40)
    seg = rng.seq(60)
    blk = rng.seq(100)
    recs = [
        ("tandem_unit", unit * 6),
        ("internal_dup", seg + rng.seq(20) + seg),
        ("block_dup", blk + blk[:30] + rng.seq(20) + blk[:30] + rng.seq(20)),
        ("low_complexity", "ACGT" * 50),
    ]
    write("reads_repeats.fq", fastq(recs))

    # ---- paired reads -----------------------------------------------------
    # Unequal mate lengths, mates below the 2*16+1 = 33 bp double-k-mer
    # signature minimum, and a duplicated pair (last pair == first pair).
    rng = Rng(0x5EED_0004)
    r1_lens = [150, 120, 80, 40, 20, 150]
    r2_lens = [100, 150, 60, 40, 25, 100]
    r1 = [rng.seq(n) for n in r1_lens]
    r2 = [rng.seq(n) for n in r2_lens]
    r1[-1] = r1[0]
    r2[-1] = r2[0]
    write("pair_r1.fq", fastq([("pair%d/1" % i, s) for i, s in enumerate(r1)]))
    write("pair_r2.fq", fastq([("pair%d/2" % i, s) for i, s in enumerate(r2)]))

    # ---- paired reads, truncated / malformed second mate ------------------
    # r2's second record has a quality line that is far too short, and r2 ends
    # after three records while r1 has five.
    rng = Rng(0x5EED_0005)
    q1 = [rng.seq(100) for _ in range(5)]
    q2_0 = rng.seq(100)
    q2_bad = rng.seq(100)
    q2_2 = rng.seq(80)
    write("pair_trunc_r1.fq", fastq([("trunc%d/1" % i, s) for i, s in enumerate(q1)]))
    write(
        "pair_trunc_r2.fq",
        fastq(
            [
                ("trunc0/2", q2_0),
                ("trunc1/2", q2_bad, "I" * 10),
                ("trunc2/2", q2_2),
            ]
        ),
    )

    # ---- genomes ----------------------------------------------------------
    # Multiple contigs (tab in the first name), a noisy contig, a tandem-repeat
    # contig and contigs shorter than / equal to / just over 2*k.
    rng = Rng(0x5EED_0006)
    write(
        "genome_multi.fasta",
        fasta(
            [
                ("contig\tone", rng.seq(1200)),
                ("contig2", noisy(rng.seq(800))),
                ("tandem", rng.seq(40) * 25),
            ]
        ),
    )
    write(
        "genome_spacing.fasta",
        fasta([("spaced", rng.seq(900)), ("spaced2", rng.seq(500))]),
    )
    write(
        "genome_short.fasta",
        fasta(
            [
                ("tiny27", rng.seq(27)),
                ("half62", rng.seq(62)),
                ("just63", rng.seq(63)),
            ]
        ),
    )


if __name__ == "__main__":
    main()
